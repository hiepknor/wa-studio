import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const defaultWorkspaceRoot = resolve(import.meta.dirname, "..");
const stableVersionPattern = /^\d+\.\d+\.\d+$/u;
const digestPattern = /^[0-9a-f]{64}$/u;
const maximumHealthBytes = 64 * 1024;
const maximumContractBytes = 64 * 1024 * 1024;
const requestTimeoutMs = 30_000;

function readJson(path, label) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw new Error(`${label} is not valid JSON: ${error.message}`);
  }
}

function componentsPath(workspaceRoot) {
  return resolve(workspaceRoot, "release/components.json");
}

function generatedReleasePath(workspaceRoot) {
  return resolve(
    workspaceRoot,
    "services/runtime/src/contracts/release/openwa-release.generated.ts",
  );
}

function reviewTestPath(workspaceRoot) {
  return resolve(
    workspaceRoot,
    "services/runtime/test/unit/openwa-contract-upgrade.spec.ts",
  );
}

function contractPath(workspaceRoot, releaseTag) {
  return resolve(
    workspaceRoot,
    "services/runtime/contracts/openwa",
    releaseTag,
    "openapi.json",
  );
}

function normalizeReleaseTag(value, label = "OpenWA release tag") {
  const releaseTag = String(value ?? "").trim().replace(/^v/u, "");
  if (!stableVersionPattern.test(releaseTag)) {
    throw new Error(`${label} must be a stable semantic version such as 0.23.3.`);
  }
  return releaseTag;
}

function normalizeServerOrigin(value) {
  let url;
  try {
    url = new URL(String(value ?? "").trim());
  } catch {
    throw new Error("OPENWA_BASE_URL must be a valid HTTP(S) origin.");
  }
  if (!["http:", "https:"].includes(url.protocol)
    || url.username || url.password || url.search || url.hash
    || !["", "/"].includes(url.pathname)) {
    throw new Error("OPENWA_BASE_URL must be an HTTP(S) origin without credentials, path, query or fragment.");
  }
  const loopback = ["127.0.0.1", "::1", "localhost"].includes(url.hostname.toLowerCase());
  if (url.protocol !== "https:" && !loopback) {
    throw new Error("OPENWA_BASE_URL must use HTTPS outside loopback development.");
  }
  return url.origin;
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function metadataFromComponents(components) {
  assert.equal(components.schemaVersion, 3, "Unsupported release component schema");
  const releaseTag = normalizeReleaseTag(components.openwaReleaseTag);
  const contractSha256 = String(components.openwaContractSha256 ?? "");
  assert(
    digestPattern.test(contractSha256),
    "OpenWA contract SHA-256 must be a lowercase 64-character digest",
  );
  return { releaseTag, contractSha256 };
}

export function renderGeneratedOpenWARelease(metadata) {
  return [
    "/* Generated by tooling/openwa-server-release.mjs. Do not edit by hand. */",
    "",
    `export const OPENWA_RELEASE_TAG = '${metadata.releaseTag}' as const;`,
    `export const OPENWA_CONTRACT_SHA256 = '${metadata.contractSha256}' as const;`,
    "",
  ].join("\n");
}

function validateContract(raw, releaseTag, expectedDigest) {
  assert.equal(
    sha256(raw),
    expectedDigest,
    `OpenWA ${releaseTag} contract digest does not match release/components.json`,
  );
  let contract;
  try {
    contract = JSON.parse(raw.toString("utf8"));
  } catch (error) {
    throw new Error(`OpenWA ${releaseTag} contract is not valid JSON: ${error.message}`);
  }
  assert.equal(contract.info?.version, releaseTag, `OpenWA ${releaseTag} contract version drifted`);
  assert.equal(typeof contract.openapi, "string", `OpenWA ${releaseTag} OpenAPI version is missing`);
  assert(contract.paths && typeof contract.paths === "object", `OpenWA ${releaseTag} paths are missing`);
  assert(
    contract.components?.schemas && typeof contract.components.schemas === "object",
    `OpenWA ${releaseTag} schemas are missing`,
  );
  return contract;
}

function readPinnedOpenWARelease(workspaceRoot) {
  const components = readJson(componentsPath(workspaceRoot), "Release components");
  const metadata = metadataFromComponents(components);
  const snapshot = contractPath(workspaceRoot, metadata.releaseTag);
  assert(existsSync(snapshot), `OpenWA ${metadata.releaseTag} contract snapshot is missing`);
  validateContract(readFileSync(snapshot), metadata.releaseTag, metadata.contractSha256);
  return { components, metadata };
}

function reviewedReleaseTag(workspaceRoot) {
  const reviewSource = readFileSync(reviewTestPath(workspaceRoot), "utf8");
  return reviewSource.match(
    /const REVIEWED_OPENWA_RELEASE = '([^']+)' as const;/u,
  )?.[1];
}

export function verifyOpenWAServerRelease({ workspaceRoot = defaultWorkspaceRoot } = {}) {
  const { metadata } = readPinnedOpenWARelease(workspaceRoot);
  assert.equal(
    readFileSync(generatedReleasePath(workspaceRoot), "utf8"),
    renderGeneratedOpenWARelease(metadata),
    "Generated OpenWA release constants are stale; promote the reviewed server release again",
  );
  assert.equal(
    reviewedReleaseTag(workspaceRoot),
    metadata.releaseTag,
    `OpenWA ${metadata.releaseTag} is pinned but its adapter contract review is not approved`,
  );
  return metadata;
}

async function readBounded(response, maximumBytes, label) {
  const declaredLength = Number(response.headers.get("content-length"));
  if (Number.isFinite(declaredLength) && declaredLength > maximumBytes) {
    await response.body?.cancel();
    throw new Error(`${label} exceeds ${maximumBytes} bytes.`);
  }
  if (!response.body) return Buffer.alloc(0);
  const reader = response.body.getReader();
  const chunks = [];
  let size = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    size += value.byteLength;
    if (size > maximumBytes) {
      await reader.cancel();
      throw new Error(`${label} exceeds ${maximumBytes} bytes.`);
    }
    chunks.push(Buffer.from(value));
  }
  return Buffer.concat(chunks);
}

async function serverRequest({ fetchImpl, origin, apiKey, path, maximumBytes, label }) {
  const response = await fetchImpl(new URL(path, origin), {
    headers: {
      accept: "application/json",
      "user-agent": "wa-studio-openwa-server-release",
      "x-api-key": apiKey,
    },
    redirect: "error",
    signal: AbortSignal.timeout(requestTimeoutMs),
  });
  if (!response.ok) {
    await response.body?.cancel();
    throw new Error(`${label} returned HTTP ${response.status}.`);
  }
  return readBounded(response, maximumBytes, label);
}

export async function probeOpenWAServer({
  baseUrl,
  apiKey,
  fetchImpl = fetch,
} = {}) {
  const origin = normalizeServerOrigin(baseUrl);
  const normalizedApiKey = String(apiKey ?? "").trim();
  if (!normalizedApiKey) throw new Error("OPENWA_API_KEY is required to identify the server release.");
  const raw = await serverRequest({
    fetchImpl,
    origin,
    apiKey: normalizedApiKey,
    path: "/api/health",
    maximumBytes: maximumHealthBytes,
    label: "OpenWA server health probe",
  });
  const health = JSON.parse(raw.toString("utf8"));
  return {
    origin,
    releaseTag: normalizeReleaseTag(
      health.version,
      "OpenWA server health version",
    ),
  };
}

function compareVersions(left, right) {
  const a = normalizeReleaseTag(left).split(".").map(Number);
  const b = normalizeReleaseTag(right).split(".").map(Number);
  for (let index = 0; index < 3; index += 1) {
    if (a[index] !== b[index]) return a[index] - b[index];
  }
  return 0;
}

export async function openWAServerReleaseStatus({
  workspaceRoot = defaultWorkspaceRoot,
  baseUrl,
  apiKey,
  fetchImpl = fetch,
} = {}) {
  const pinned = verifyOpenWAServerRelease({ workspaceRoot });
  const observed = await probeOpenWAServer({ baseUrl, apiKey, fetchImpl });
  const comparison = compareVersions(observed.releaseTag, pinned.releaseTag);
  return {
    origin: observed.origin,
    status: comparison > 0 ? "upgrade_available" : comparison === 0 ? "current" : "server_behind",
    pinnedTag: pinned.releaseTag,
    observedTag: observed.releaseTag,
  };
}

function atomicWrite(path, value) {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.tmp-${process.pid}`;
  writeFileSync(temporary, value, { flag: "wx" });
  renameSync(temporary, path);
}

export async function syncOpenWAServerRelease({
  workspaceRoot = defaultWorkspaceRoot,
  baseUrl,
  apiKey,
  contractFile,
  fetchImpl = fetch,
} = {}) {
  const current = verifyOpenWAServerRelease({ workspaceRoot });
  const observed = await probeOpenWAServer({ baseUrl, apiKey, fetchImpl });
  if (compareVersions(observed.releaseTag, current.releaseTag) < 0) {
    throw new Error(
      `Refusing to downgrade the reviewed OpenWA pin from ${current.releaseTag} to server ${observed.releaseTag}.`,
    );
  }
  const raw = contractFile
    ? readFileSync(resolve(contractFile))
    : await serverRequest({
        fetchImpl,
        origin: observed.origin,
        apiKey: String(apiKey).trim(),
        path: "/api/docs-json",
        maximumBytes: maximumContractBytes,
        label: `OpenWA ${observed.releaseTag} server OpenAPI document`,
      });
  const contractSha256 = sha256(raw);
  validateContract(raw, observed.releaseTag, contractSha256);
  const destination = contractPath(workspaceRoot, observed.releaseTag);
  if (existsSync(destination)) {
    assert.equal(
      sha256(readFileSync(destination)),
      contractSha256,
      `Refusing to overwrite a different OpenWA ${observed.releaseTag} contract snapshot`,
    );
  } else {
    atomicWrite(destination, raw);
  }
  return {
    contractSha256,
    origin: observed.origin,
    pinnedTag: current.releaseTag,
    releaseTag: observed.releaseTag,
  };
}

export async function promoteOpenWAServerRelease({
  workspaceRoot = defaultWorkspaceRoot,
  baseUrl,
  apiKey,
  fetchImpl = fetch,
} = {}) {
  const { components, metadata: current } = readPinnedOpenWARelease(workspaceRoot);
  const observed = await probeOpenWAServer({ baseUrl, apiKey, fetchImpl });
  if (compareVersions(observed.releaseTag, current.releaseTag) < 0) {
    throw new Error(
      `Refusing to downgrade the reviewed OpenWA pin from ${current.releaseTag} to server ${observed.releaseTag}.`,
    );
  }
  assert.equal(
    reviewedReleaseTag(workspaceRoot),
    observed.releaseTag,
    `OpenWA ${observed.releaseTag} cannot be promoted until its adapter contract review is approved`,
  );
  const snapshot = contractPath(workspaceRoot, observed.releaseTag);
  assert(
    existsSync(snapshot),
    `OpenWA ${observed.releaseTag} contract snapshot is not staged; run npm run openwa:server:sync`,
  );
  const raw = readFileSync(snapshot);
  const next = {
    releaseTag: observed.releaseTag,
    contractSha256: sha256(raw),
  };
  validateContract(raw, next.releaseTag, next.contractSha256);

  // Write generated consumers first so an interrupted promotion can be safely retried.
  atomicWrite(generatedReleasePath(workspaceRoot), renderGeneratedOpenWARelease(next));
  atomicWrite(componentsPath(workspaceRoot), `${JSON.stringify({
    ...components,
    openwaReleaseTag: next.releaseTag,
    openwaContractSha256: next.contractSha256,
  }, null, 2)}\n`);
  verifyOpenWAServerRelease({ workspaceRoot });
  return { ...next, origin: observed.origin };
}

function argument(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

function connectionOptions() {
  return {
    baseUrl: argument("base-url") ?? process.env.OPENWA_BASE_URL,
    apiKey: process.env.OPENWA_API_KEY,
  };
}

async function main() {
  const command = process.argv[2];
  if (command === "verify") {
    const metadata = verifyOpenWAServerRelease();
    process.stdout.write(
      `Verified reviewed OpenWA ${metadata.releaseTag} contract (${metadata.contractSha256}).\n`,
    );
    return;
  }
  if (command === "status") {
    const status = await openWAServerReleaseStatus(connectionOptions());
    if (process.argv.includes("--json")) {
      process.stdout.write(`${JSON.stringify(status, null, 2)}\n`);
    } else if (status.status === "upgrade_available") {
      process.stdout.write(
        `OpenWA server ${status.origin} reports ${status.observedTag}; WA Studio is pinned to ${status.pinnedTag}.\n`,
      );
    } else {
      process.stdout.write(
        `OpenWA server ${status.origin} reports ${status.observedTag}; pin status: ${status.status}.\n`,
      );
    }
    return;
  }
  if (command === "sync") {
    const synchronized = await syncOpenWAServerRelease({
      ...connectionOptions(),
      contractFile: argument("contract"),
    });
    process.stdout.write(
      `Staged OpenWA ${synchronized.releaseTag} from ${synchronized.origin} `
      + `(${synchronized.contractSha256}).\n`
      + `The reviewed pin remains ${synchronized.pinnedTag}; review the adapter before promotion.\n`,
    );
    return;
  }
  if (command === "promote") {
    const promoted = await promoteOpenWAServerRelease(connectionOptions());
    process.stdout.write(
      `Promoted reviewed OpenWA ${promoted.releaseTag} from ${promoted.origin} `
      + `(${promoted.contractSha256}).\n`,
    );
    return;
  }
  throw new Error(
    "Usage: openwa-server-release.mjs <verify|status|sync|promote> [--base-url <origin>] [--contract <openapi.json>] [--json]",
  );
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : undefined;
if (invokedPath === fileURLToPath(import.meta.url)) {
  main().catch(error => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
